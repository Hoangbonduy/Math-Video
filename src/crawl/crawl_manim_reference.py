#!/usr/bin/env python3
"""Download Manim 0.22.1's reference manual into a Markdown hierarchy.

From Math-Video:
    python3 -m pip install beautifulsoup4 markdownify requests
    python3 src/crawl/crawl_manim_reference.py

The default delay is 1 second between requests. Downloaded HTML is cached, so
rerunning resumes an interrupted download. Use --help for available options.
"""
import argparse
import hashlib
import os
import re
import sys
import time
from pathlib import Path
from urllib.parse import urldefrag, urljoin

try:
    import requests
    from bs4 import BeautifulSoup
    from markdownify import markdownify
except ImportError:
    sys.exit('Missing packages. Install with: python3 -m pip install beautifulsoup4 markdownify requests')

BASE = 'https://docs.manim.community/en/v0.22.1/'
PROJECT = Path(__file__).resolve().parents[2]
GROUPS = {
    'Animations': 'animations', 'Cameras': 'cameras',
    'Configuration': 'configuration', 'Mobjects': 'mobjects',
    'Scenes': 'scenes', 'Utilities and other modules': 'utilities',
}
MARKER = '<!-- Generated by crawl_manim_reference.py -->'


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--output', type=Path, default=PROJECT / 'references' / 'manim-0.22.1')
    parser.add_argument('--cache', type=Path, default=PROJECT / '.cache' / 'manim-0.22.1')
    parser.add_argument('--delay', type=float, default=1.0, help='seconds between network requests (default: 1)')
    args = parser.parse_args()
    if args.delay < 0:
        parser.error('--delay must be non-negative')
    output, cache = args.output.resolve(), args.cache.resolve()
    marker = output / '.manim-reference-generated'
    if output.exists() and any(output.iterdir()) and not marker.is_file():
        sys.exit(f'Refusing to overwrite existing directory without generator marker: {output}')
    cache.mkdir(parents=True, exist_ok=True)
    session = requests.Session()
    session.headers['User-Agent'] = 'ManimReferencePersonalArchive/1.0 (documentation downloader)'
    last_request = 0.0

    def download(url):
        nonlocal last_request
        filename = cache / (hashlib.sha256(url.encode()).hexdigest() + '.html')
        if filename.is_file():
            return filename.read_bytes()
        for attempt in range(3):
            remaining = args.delay - (time.monotonic() - last_request)
            if remaining > 0:
                time.sleep(remaining)
            try:
                last_request = time.monotonic()
                response = session.get(url, timeout=45)
                if response.status_code == 429:
                    sys.exit('The documentation server returned HTTP 429 (rate limit). '
                             'Please wait and rerun; cached pages will be reused.')
                response.raise_for_status()
                if not BeautifulSoup(response.content, 'html.parser').select_one('article'):
                    raise ValueError('The response does not contain the expected documentation article')
                filename.write_bytes(response.content)
                return response.content
            except (requests.RequestException, ValueError) as exc:
                if attempt == 2:
                    sys.exit(f'Failed to download {url}: {exc}\nRerun to resume from cache.')
                print(f'Retrying {url}: {exc}', file=sys.stderr)
                time.sleep(3 * (attempt + 1))

    ref = BeautifulSoup(download(urljoin(BASE, 'reference.html')), 'html.parser')
    link = next((a for a in ref.select('.sidebar-tree a')
                 if a.get_text(strip=True) == 'Reference Manual'), None)
    if not link or not link.parent.find('ul', recursive=False):
        sys.exit('Could not find the Reference Manual navigation tree.')
    nodes = []

    def walk(li, group=None, segments=()):
        a = li.find('a', recursive=False)
        if not a:
            return
        name, href = a.get_text(' ', strip=True), a.get('href', '')
        if group is None:
            group = GROUPS.get(name)
            if not group:
                sys.exit(f'Unknown top-level group: {name!r}. Update GROUPS before continuing.')
        else:
            if name in ('.', '..') or '/' in name or '\\' in name:
                sys.exit(f'Unsafe navigation name: {name!r}')
            segments += (name,)
        nodes.append({'name': name, 'href': href, 'group': group, 'segments': segments})
        ul = li.find('ul', recursive=False)
        if ul:
            for child in ul.find_all('li', recursive=False):
                walk(child, group, segments)

    for li in link.parent.find('ul', recursive=False).find_all('li', recursive=False):
        walk(li)
    print(f'Found {len(nodes)} group, module and class pages.', flush=True)
    for number, node in enumerate(nodes, 1):
        url = urljoin(BASE, node['href'])
        soup = BeautifulSoup(download(url), 'html.parser')
        article = soup.select_one('article').extract()
        node['article'] = article
        page = node['href'].split('/')[-1].removesuffix('.html')
        is_class = bool(article.select_one('dl.py.class > dt.sig') and page.endswith('.' + node['name']))
        node['kind'] = 'class' if is_class else ('group' if not node['segments'] else 'module')
        path = Path(node['group']).joinpath(*node['segments'])
        node['path'] = path.parent / (path.name + '.md') if is_class else path / 'INDEX.md'
        print(f'[{number}/{len(nodes)}] {node["href"]}', flush=True)
    by_url = {urldefrag(urljoin(BASE, n['href']))[0]: n for n in nodes}

    def render(element, source, dest):
        soup = BeautifulSoup(str(element), 'html.parser')
        for item in soup.select('.headerlink, pre[data-manim-binder], .viewcode-link'):
            item.decompose()
        for item in soup.select('video'):
            src = item.get('src')
            item.replace_with(soup.new_string('[Video example](' + urljoin(source, src) + ')') if src else '')
        for item in soup.select('a[href]'):
            url = urljoin(source, item['href'])
            page, fragment = urldefrag(url)
            if page in by_url and not fragment:
                item['href'] = os.path.relpath(output / by_url[page]['path'], (output / dest).parent).replace(os.sep, '/')
            else:
                item['href'] = url
        for item in soup.select('img[src]'):
            item['src'] = urljoin(source, item['src'])
        return re.sub(r'\n{4,}', '\n\n\n', markdownify(str(soup), heading_style='ATX', bullets='-')).strip() + '\n'

    def write(path, content):
        dest = output / path
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(MARKER + '\n\n' + content, encoding='utf-8')

    output.mkdir(parents=True, exist_ok=True)
    marker.write_text('Generated Manim reference; do not remove if you want to rerun the crawler.\n', encoding='utf-8')
    function_count = 0
    for node in nodes:
        source, dest, article = urljoin(BASE, node['href']), node['path'], node['article']
        children = [x for x in nodes if x['group'] == node['group']
                    and len(x['segments']) == len(node['segments']) + 1
                    and x['segments'][:-1] == node['segments']]
        listing = '\n## Mục con\n\n' if children else ''
        for child in children:
            relative = os.path.relpath(output / child['path'], (output / dest).parent).replace(os.sep, '/')
            desc = child['article'].select_one('section > p:not(.rubric)')
            summary = ' '.join(desc.get_text(' ', strip=True).split()) if desc else ''
            listing += f'- [{child["name"]}]({relative})' + (f' — {summary}' if 0 < len(summary) < 250 else '') + '\n'
        functions = []
        if node['kind'] == 'module':
            for dl in article.select('dl.py.function'):
                if dl.find_parent('dl', class_='py'):
                    continue
                dt = dl.find('dt', recursive=False)
                ident = dt.get('id', '') if dt else ''
                name = ident.rsplit('.', 1)[-1]
                if not re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*', name):
                    continue
                path = dest.parent / (name + '.md')
                write(path, f'# {name}\n\nNguồn: [{ident}]({source}#{ident})\n\n' + render(dl, source, path))
                functions.append((name, path))
                function_count += 1
        if functions:
            listing += '\n## Functions\n\n' + ''.join(f'- [{name}]({path.name})\n' for name, path in functions)
        write(dest, f'Nguồn: [{node["name"]}]({source})\n\n' + render(article, source, dest) + listing)
    lines = ['# Manim Community 0.22.1 — Reference Manual', '',
             f'Nguồn: [{BASE}reference.html]({BASE}reference.html)', '',
             'Nội dung gốc bằng tiếng Anh. Các package lồng nhau được giữ nguyên; method nằm trong tệp class, function của module có tệp riêng. Hình ảnh, video và liên kết tới anchor có thể cần kết nối mạng.', '', '## Nhóm', '']
    lines.extend(f'- [{n["name"]}]({n["path"].as_posix()})' for n in nodes if n['kind'] == 'group')
    write(Path('INDEX.md'), '\n'.join(lines) + '\n')
    print(f'Finished: {len(nodes)} pages, {function_count} separate functions. Output: {output}')


if __name__ == '__main__':
    try:
        main()
    except KeyboardInterrupt:
        sys.exit('\nInterrupted. Run again to resume from cache.')
